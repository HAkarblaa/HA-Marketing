-- ---------------------------------------------------------
-- 9) صلاحية البائع - إنشاء وإدارة متجره
-- ---------------------------------------------------------
do $$
begin
  if to_regclass('public.shop_businesses') is not null then
    execute 'alter table public.shop_businesses enable row level security';
    execute 'drop policy if exists "seller own businesses" on public.shop_businesses';
    execute $p$
      create policy "seller own businesses"
      on public.shop_businesses
      for all
      to authenticated
      using(
        (owner_user_id=auth.uid() and public.has_approved_role('seller'))
        or public.ha_is_admin()
      )
      with check(
        (owner_user_id=auth.uid() and public.has_approved_role('seller'))
        or public.ha_is_admin()
      )
    $p$;
    execute 'grant select,insert,update,delete on public.shop_businesses to authenticated';
  end if;
end $$;

