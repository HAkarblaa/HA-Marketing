-- ---------------------------------------------------------
-- 3) دالة أدمن آمنة
-- تستخدم is_super_admin() الحالية إذا كانت موجودة
-- ---------------------------------------------------------
create or replace function public.ha_is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path=public
as $$
declare
  v boolean := false;
begin
  if to_regprocedure('public.is_super_admin()') is not null then
    execute 'select public.is_super_admin()' into v;
    return coalesce(v,false);
  end if;
  return false;
end;
$$;

grant execute on function public.ha_is_admin() to authenticated;

-- ---------------------------------------------------------
-- 4) إرسال/تحديث طلب صلاحية واحد من داخل التطبيق
-- هذه هي الدالة التي تعتمد عليها كل الأنواع
-- ---------------------------------------------------------
create or replace function public.request_marketplace_role(
  p_role text,
  p_display_name text default null,
  p_phone text default null,
  p_governorate text default null,
  p_address text default null,
  p_details text default null,
  p_vehicle_type text default null,
  p_vehicle_model text default null,
  p_vehicle_color text default null,
  p_plate_number text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid := auth.uid();
  v_id text;
  v_status text;
  v_transport_count integer := 0;
begin
  if v_uid is null then
    raise exception 'يجب تسجيل الدخول أولاً';
  end if;

  if p_role not in (
    'seller',
    'service_provider',
    'sports_manager',
    'games_manager',
    'taxi_driver',
    'delivery_driver'
  ) then
    raise exception 'نوع الصلاحية غير صحيح: %', p_role;
  end if;

  -- نستخدم آخر طلب لنفس الدور إن وجد.
  select id::text,status
    into v_id,v_status
  from public.marketplace_applications
  where user_id=v_uid
    and role_type=p_role
  order by created_at desc nulls last
  limit 1;

  if v_id is null then
    insert into public.marketplace_applications(
      user_id,role_type,display_name,phone,governorate,address,details,status,updated_at
    )
    values(
      v_uid,p_role,p_display_name,p_phone,p_governorate,p_address,p_details,'pending',now()
    )
    returning id::text,status into v_id,v_status;
  else
    -- إذا الصلاحية مقبولة لا نلغيها بسبب إعادة فتح النموذج.
    update public.marketplace_applications
    set
      display_name=coalesce(p_display_name,display_name),
      phone=coalesce(p_phone,phone),
      governorate=coalesce(p_governorate,governorate),
      address=coalesce(p_address,address),
      details=coalesce(p_details,details),
      status=case when status='approved' then 'approved' else 'pending' end,
      admin_note=case when status='approved' then admin_note else null end,
      updated_at=now()
    where id::text=v_id
    returning status into v_status;
  end if;

  -- سائق/مندوب: خزّن بيانات المركبة كـ pending بانتظار موافقة الإدارة.
  if p_role in ('taxi_driver','delivery_driver') then

    update public.transport_profiles
    set
      full_name=coalesce(p_display_name,full_name),
      phone=coalesce(p_phone,phone),
      vehicle_type=coalesce(p_vehicle_type,vehicle_type),
      vehicle_model=coalesce(p_vehicle_model,vehicle_model),
      vehicle_color=coalesce(p_vehicle_color,vehicle_color),
      plate_number=coalesce(p_plate_number,plate_number),
      governorate=coalesce(p_governorate,governorate),
      status=case when status='approved' then 'approved' else 'pending' end,
      updated_at=now()
    where user_id=v_uid
      and role_type=p_role;

    get diagnostics v_transport_count = row_count;

    if v_transport_count=0 then
      insert into public.transport_profiles(
        user_id,role_type,full_name,phone,vehicle_type,vehicle_model,
        vehicle_color,plate_number,governorate,status,updated_at
      )
      values(
        v_uid,p_role,p_display_name,p_phone,p_vehicle_type,p_vehicle_model,
        p_vehicle_color,p_plate_number,p_governorate,'pending',now()
      );
    end if;

  end if;

  return jsonb_build_object(
    'ok',true,
    'id',v_id,
    'role_type',p_role,
    'status',v_status
  );
end;
$$;

grant execute on function public.request_marketplace_role(
  text,text,text,text,text,text,text,text,text,text
) to authenticated;

-- ---------------------------------------------------------
-- 5) التحقق من الصلاحية المعتمدة
-- ---------------------------------------------------------
create or replace function public.has_approved_role(p_role text)
returns boolean
language sql
stable
security definer
set search_path=public
as $$
  select
    public.ha_is_admin()
    or exists(
      select 1
      from public.marketplace_applications m
      where m.user_id=auth.uid()
        and m.role_type=p_role
        and m.status='approved'
    )
    or (
      p_role in ('taxi_driver','delivery_driver')
      and exists(
        select 1
        from public.transport_profiles t
        where t.user_id=auth.uid()
          and t.role_type=p_role
          and t.status='approved'
      )
    );
$$;

grant execute on function public.has_approved_role(text) to authenticated;

-- ---------------------------------------------------------
-- 6) مراجعة الأدمن للطلب
-- ID كنص حتى يشتغل سواء كان bigint أو uuid
-- ---------------------------------------------------------
create or replace function public.admin_review_marketplace_application(
  p_id text,
  p_status text,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid;
  v_role text;
begin
  if not public.ha_is_admin() then
    raise exception 'هذه العملية للأدمن الرئيسي فقط';
  end if;

  if p_status not in ('pending','approved','rejected','suspended') then
    raise exception 'حالة الطلب غير صحيحة';
  end if;

  update public.marketplace_applications
  set status=p_status,
      admin_note=p_note,
      updated_at=now()
  where id::text=p_id
  returning user_id,role_type into v_uid,v_role;

  if v_uid is null then
    raise exception 'الطلب غير موجود';
  end if;

  if v_role in ('taxi_driver','delivery_driver') then
    update public.transport_profiles
    set status=p_status,
        updated_at=now()
    where user_id=v_uid
      and role_type=v_role;
  end if;

  return jsonb_build_object(
    'ok',true,
    'id',p_id,
    'status',p_status,
    'role_type',v_role
  );
end;
$$;

grant execute on function public.admin_review_marketplace_application(
  text,text,text
) to authenticated;

