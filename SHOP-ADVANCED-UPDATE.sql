create or replace function public.create_shop_order_v3(
  p_customer_name text,
  p_phone text,
  p_governorate text,
  p_address text,
  p_notes text,
  p_items jsonb,
  p_payment_method text default 'cash_on_delivery',
  p_coupon_code text default null
) returns bigint
language plpgsql security definer set search_path=public as $$
declare
  v_order bigint; v_item jsonb; v_product public.products%rowtype; v_qty int;
  v_subtotal bigint:=0; v_delivery bigint:=0; v_discount bigint:=0; v_total bigint:=0;
  v_method text; v_coupon public.shop_coupons%rowtype; v_price bigint; v_option text;
begin
  if auth.uid() is null then raise exception 'Login required'; end if;
  if coalesce(trim(p_customer_name),'')='' or coalesce(trim(p_phone),'')='' or coalesce(trim(p_address),'')='' then raise exception 'Customer name, phone and address are required'; end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'Cart is empty'; end if;
  v_method:=case when p_payment_method='electronic' then 'electronic' else 'cash_on_delivery' end;

  select fee into v_delivery from public.shop_delivery_fees where governorate=trim(coalesce(p_governorate,'')) and is_active=true;
  v_delivery:=coalesce(v_delivery,0);

  insert into public.shop_orders(customer_id,customer_name,phone,governorate,address,notes,payment_method,payment_status,delivery_fee)
  values(auth.uid(),trim(p_customer_name),trim(p_phone),nullif(trim(p_governorate),''),trim(p_address),nullif(trim(p_notes),''),v_method,'pending',v_delivery)
  returning id into v_order;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty:=greatest(1,coalesce((v_item->>'quantity')::int,1));
    v_option:=nullif(trim(coalesce(v_item->>'option_text','')),'');
    select * into v_product from public.products where id=(v_item->>'product_id')::bigint and is_active=true for update;
    if not found then raise exception 'Product unavailable'; end if;
    if v_qty < coalesce(v_product.min_order_qty,1) then raise exception 'Minimum quantity for % is %',v_product.name,v_product.min_order_qty; end if;
    if v_product.stock<v_qty then raise exception 'Insufficient stock for %',v_product.name; end if;
    v_price:=coalesce(v_product.discount_price,v_product.price);
    if v_price<0 then v_price:=v_product.price; end if;
    update public.products set stock=stock-v_qty,updated_at=now() where id=v_product.id;
    insert into public.shop_order_items(order_id,product_id,product_name,quantity,unit_price,subtotal,option_text)
    values(v_order,v_product.id,v_product.name,v_qty,v_price,v_price*v_qty,v_option);
    v_subtotal:=v_subtotal+(v_price*v_qty);
  end loop;

  if nullif(trim(coalesce(p_coupon_code,'')),'') is not null then
    select * into v_coupon from public.shop_coupons
    where upper(code)=upper(trim(p_coupon_code)) and is_active=true
      and (starts_at is null or starts_at<=now()) and (expires_at is null or expires_at>=now())
    limit 1;
    if found and v_subtotal>=v_coupon.min_total then
      if v_coupon.discount_type='percent' then
        v_discount:=floor(v_subtotal * least(v_coupon.discount_value,100)::numeric / 100);
      else
        v_discount:=v_coupon.discount_value;
      end if;
      if v_coupon.max_discount is not null then v_discount:=least(v_discount,v_coupon.max_discount); end if;
      v_discount:=least(v_discount,v_subtotal);
    end if;
  end if;

  v_total:=greatest(0,v_subtotal+v_delivery-v_discount);
  update public.shop_orders set subtotal=v_subtotal,delivery_fee=v_delivery,discount_amount=v_discount,
    coupon_code=case when v_discount>0 then upper(trim(p_coupon_code)) else null end,
    total=v_total,updated_at=now() where id=v_order;
  return v_order;
end$$;

grant execute on function public.create_shop_order_v3(text,text,text,text,text,jsonb,text,text) to authenticated;

create or replace function public.cancel_shop_order(p_order_id bigint,p_reason text default null) returns void
language plpgsql security definer set search_path=public as $$
declare r record;
begin
  if auth.uid() is null then raise exception 'Login required'; end if;
  if not exists(select 1 from public.shop_orders where id=p_order_id and customer_id=auth.uid() and status in('new','confirmed')) then raise exception 'Order cannot be cancelled'; end if;
  for r in select product_id,quantity from public.shop_order_items where order_id=p_order_id loop
    if r.product_id is not null then update public.products set stock=stock+r.quantity,updated_at=now() where id=r.product_id; end if;
  end loop;
  update public.shop_orders set status='cancelled',cancel_reason=nullif(trim(coalesce(p_reason,'')),''),updated_at=now() where id=p_order_id;
end$$;
grant execute on function public.cancel_shop_order(bigint,text) to authenticated;

