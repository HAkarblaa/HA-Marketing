create table if not exists public.shop_favorites(
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id,product_id)
);

create table if not exists public.shop_product_reviews(
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  rating int not null check(rating between 1 and 5),
  comment text,
  is_visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id,product_id)
);

create table if not exists public.shop_saved_addresses(
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null default 'العنوان',
  governorate text,
  address text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.shop_coupons(
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_type text not null check(discount_type in('percent','fixed')),
  discount_value bigint not null check(discount_value>=0),
  min_total bigint not null default 0,
  max_discount bigint,
  starts_at timestamptz,
  expires_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.shop_delivery_fees(
  governorate text primary key,
  fee bigint not null default 0 check(fee>=0),
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

