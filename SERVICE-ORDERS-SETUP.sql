create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references auth.users(id) on delete cascade,
  department text not null default 'services',
  order_type text not null,
  description text,
  phone text,
  area text,
  customer_lat double precision,
  customer_lng double precision,
  employee_lat double precision,
  employee_lng double precision,
  attachment_url text,
  status text not null default 'new',
  assigned_employee_id uuid references auth.users(id) on delete set null,
  cancel_reason text,
  customer_rating int check (customer_rating between 1 and 5),
  employee_rating int check (employee_rating between 1 and 5),
  customer_review text,
  employee_review text,
  accepted_at timestamptz,
  on_the_way_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

