alter table public.orders enable row level security;

drop policy if exists "customers insert own orders" on public.orders;
create policy "customers insert own orders" on public.orders for insert to authenticated
with check (
  auth.uid() = customer_id
  and exists(select 1 from public.profiles p where p.id=auth.uid() and p.account_type='customer')
);

drop policy if exists "customers read own orders" on public.orders;
create policy "customers read own orders" on public.orders for select to authenticated
using (auth.uid() = customer_id);

drop policy if exists "employees read matching service orders" on public.orders;
create policy "employees read matching service orders" on public.orders for select to authenticated
using (
  exists (
    select 1 from public.profiles p
    join public.employee_roles r on r.id=p.employee_role_id
    where p.id=auth.uid() and p.account_type='employee' and p.employee_status='approved'
      and r.is_active=true and r.department=orders.department
      and (orders.assigned_employee_id is null or orders.assigned_employee_id=auth.uid())
  )
);

create or replace function public.customer_cancel_order(p_order_id bigint, p_reason text)
returns void language plpgsql security definer set search_path=public as $$
begin
  update public.orders set status='cancelled', cancel_reason=nullif(trim(p_reason),''), cancelled_at=now(), updated_at=now()
  where id=p_order_id and customer_id=auth.uid() and status in ('new','accepted');
  if not found then raise exception 'Order cannot be cancelled'; end if;
end; $$;
grant execute on function public.customer_cancel_order(bigint,text) to authenticated;

create or replace function public.employee_update_order(p_order_id bigint, p_status text, p_assign_to_me boolean default false)
returns void language plpgsql security definer set search_path=public as $$
declare v_dept text; v_assigned uuid; v_current text;
begin
  select department,assigned_employee_id,status into v_dept,v_assigned,v_current from public.orders where id=p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if not exists(select 1 from public.profiles p join public.employee_roles r on r.id=p.employee_role_id
    where p.id=auth.uid() and p.account_type='employee' and p.employee_status='approved' and r.is_active=true and r.department=v_dept)
  then raise exception 'Not allowed'; end if;

  if p_status='accepted' then
    if v_assigned is not null and v_assigned<>auth.uid() then raise exception 'Order already assigned'; end if;
    update public.orders set assigned_employee_id=auth.uid(),status='accepted',accepted_at=coalesce(accepted_at,now()),updated_at=now() where id=p_order_id;
  elsif p_status='on_the_way' then
    if v_assigned<>auth.uid() or v_current<>'accepted' then raise exception 'Invalid status change'; end if;
    update public.orders set status='on_the_way',on_the_way_at=now(),updated_at=now() where id=p_order_id;
  elsif p_status='completed' then
    if v_assigned<>auth.uid() or v_current<>'on_the_way' then raise exception 'Invalid status change'; end if;
    update public.orders set status='completed',completed_at=now(),updated_at=now() where id=p_order_id;
  elsif p_status='cancelled' then
    if v_assigned<>auth.uid() or v_current not in ('accepted','on_the_way') then raise exception 'Invalid status change'; end if;
    update public.orders set status='cancelled',cancelled_at=now(),updated_at=now() where id=p_order_id;
  else raise exception 'Invalid status'; end if;
end; $$;
grant execute on function public.employee_update_order(bigint,text,boolean) to authenticated;

create or replace function public.employee_update_location(p_order_id bigint,p_lat double precision,p_lng double precision)
returns void language plpgsql security definer set search_path=public as $$
begin
  update public.orders set employee_lat=p_lat,employee_lng=p_lng,updated_at=now()
  where id=p_order_id and assigned_employee_id=auth.uid() and status='on_the_way';
  if not found then raise exception 'Not allowed'; end if;
end; $$;
grant execute on function public.employee_update_location(bigint,double precision,double precision) to authenticated;

create or replace function public.customer_rate_order(p_order_id bigint,p_rating int,p_review text default null)
returns void language plpgsql security definer set search_path=public as $$
begin
  if p_rating not between 1 and 5 then raise exception 'Rating must be 1-5'; end if;
  update public.orders set customer_rating=p_rating,customer_review=nullif(trim(p_review),''),updated_at=now()
  where id=p_order_id and customer_id=auth.uid() and status='completed';
  if not found then raise exception 'Not allowed'; end if;
end; $$;
grant execute on function public.customer_rate_order(bigint,int,text) to authenticated;

