create or replace function public.enforce_username_change_cooldown()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare v_super boolean := false;
begin
  if old.username is distinct from new.username then
    select exists(
      select 1 from public.app_admins a
      where a.user_id=auth.uid() and a.is_active=true and coalesce(a.is_super_admin,false)=true
    ) into v_super;
    if old.username_changed_at is not null
       and old.username_changed_at > now()-interval '30 days'
       and not v_super then
      raise exception 'يمكن تغيير المعرف مرة واحدة كل 30 يوم';
    end if;
    new.username_changed_at=now();
  end if;
  return new;
end$$;

drop trigger if exists trg_profiles_username_cooldown on public.profiles;
create trigger trg_profiles_username_cooldown
before update of username on public.profiles
for each row execute function public.enforce_username_change_cooldown();

create or replace function public.set_my_security_pin(p_pin text)
returns void
language plpgsql
security definer
set search_path=public,extensions
as $$
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول أولاً'; end if;
  if p_pin !~ '^[0-9]{6}$' then raise exception 'الرمز الخاص يجب أن يكون 6 أرقام'; end if;
  update public.profiles
     set pin_hash=extensions.crypt(p_pin,extensions.gen_salt('bf')), pin_updated_at=now()
   where id=auth.uid();
end$$;
grant execute on function public.set_my_security_pin(text) to authenticated;

create or replace function public.verify_my_security_pin(p_pin text)
returns boolean
language sql
security definer
set search_path=public,extensions
as $$
  select coalesce((
    select pin_hash is not null and extensions.crypt(p_pin,pin_hash)=pin_hash
    from public.profiles where id=auth.uid()
  ),false)
$$;
grant execute on function public.verify_my_security_pin(text) to authenticated;

