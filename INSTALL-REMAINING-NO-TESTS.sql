-- 3) Final shop courier functions
create or replace function public.update_shop_delivery_status(p_delivery_id bigint,p_status text,p_otp text default null)
returns void language plpgsql security definer set search_path=public as $$
declare d public.shop_order_deliveries%rowtype;
begin
  if not public.has_approved_role('delivery_driver') then raise exception 'غير مصرح كمندوب'; end if;
  select * into d from public.shop_order_deliveries where id=p_delivery_id and driver_id=auth.uid() for update;
  if not found then raise exception 'التوصيل غير موجود'; end if;
  if p_status='picked_up' and d.status<>'accepted' then raise exception 'يجب قبول الطلب أولاً'; end if;
  if p_status='on_the_way' and d.status<>'picked_up' then raise exception 'يجب تسجيل الاستلام أولاً'; end if;
  if p_status='delivered' then
    if d.status<>'on_the_way' then raise exception 'يجب أن يكون الطلب بالطريق أولاً'; end if;
    if trim(coalesce(p_otp,''))<>d.otp_code then raise exception 'رمز التسليم غير صحيح'; end if;
  end if;
  if p_status not in('picked_up','on_the_way','delivered') then raise exception 'حالة غير صحيحة'; end if;
  update public.shop_order_deliveries set status=p_status,
    picked_up_at=case when p_status='picked_up' then now() else picked_up_at end,
    delivered_at=case when p_status='delivered' then now() else delivered_at end,
    updated_at=now() where id=p_delivery_id;
  if p_status in('picked_up','on_the_way') then
    update public.shop_orders set status='out_for_delivery',updated_at=now() where id=d.order_id and status<>'cancelled';
  elsif p_status='delivered' then
    if not exists(select 1 from public.shop_order_deliveries x where x.order_id=d.order_id and x.status not in('delivered','cancelled')) then
      update public.shop_orders set status='completed',updated_at=now() where id=d.order_id and status<>'cancelled';
    end if;
  end if;
end$$;
grant execute on function public.update_shop_delivery_status(bigint,text,text) to authenticated;

create or replace function public.get_my_shop_deliveries()
returns jsonb language sql stable security definer set search_path=public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',d.id,'order_id',d.order_id,'status',d.status,'pickup_name',d.pickup_name,'otp_code',
      case when d.status in('picked_up','on_the_way') then d.otp_code else null end,
    'driver_id',d.driver_id,
    'driver_name',to_jsonb(tp)->>'full_name',
    'driver_phone',to_jsonb(tp)->>'phone',
    'vehicle_type',to_jsonb(tp)->>'vehicle_type',
    'vehicle_model',to_jsonb(tp)->>'vehicle_model',
    'vehicle_color',to_jsonb(tp)->>'vehicle_color',
    'plate_number',to_jsonb(tp)->>'plate_number',
    'accepted_at',d.accepted_at,'picked_up_at',d.picked_up_at,'delivered_at',d.delivered_at
  ) order by d.created_at desc),'[]'::jsonb)
  from public.shop_order_deliveries d
  left join public.transport_profiles tp on tp.user_id=d.driver_id
  where d.customer_id=auth.uid();
$$;
grant execute on function public.get_my_shop_deliveries() to authenticated;

